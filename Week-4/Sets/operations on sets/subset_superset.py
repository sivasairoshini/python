#Program:To check whether one set is a subset or superset of another set using issubset() and issuperset().
s1={57,47,89,96,25,45,18,33,88}
s2={57,45,88}
print("s2 is subset of s1??",s2.issubset(s1))
print("s1 is superset of s2??",s1.issuperset(s2))
#output
#s2 is subset of s1?? True
#s1 is superset of s2?? True