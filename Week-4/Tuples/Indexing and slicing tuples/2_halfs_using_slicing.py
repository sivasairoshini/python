#Program:Slicing to print the first half and the second half separately.
t=(1,2,5,7,6,4,3,9,8,57,64,34,38)
print("Tuple:",t)
print("1st half:",t[0:7])
print("2nd half:",t[7:])
#output
#Tuple: (1, 2, 5, 7, 6, 4, 3, 9, 8, 57, 64, 34, 38)
#1st half: (1, 2, 5, 7, 6, 4, 3)
#2nd half: (9, 8, 57, 64, 34, 38)