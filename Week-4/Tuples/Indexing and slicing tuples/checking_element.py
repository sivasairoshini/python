#Program: To check whether a given value exists in a tuple, using the in keyword.
t=("Roshini","Raju","Neeraja","Ram","Bhavitha")
print("tuple:",t)
if "Ram" in t:
    print("Ram is in the tuple")
else:
    print("Ram is not in the tuple")
#output
#tuple: ('Roshini', 'Raju', 'Neeraja', 'Ram', 'Bhavitha')
#Ram is in the tuple