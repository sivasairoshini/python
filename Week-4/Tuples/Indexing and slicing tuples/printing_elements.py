#Program:printing the elements at index 0, index 5, and the last element using positive and negative indexing.
t=(1,2,5,7,6,4,3,9,8,57)
print("Tuple:",t)
print("Element at index 0:",t[0])
print("Element at index 5",t[5])
print("Last element using negative indexing is t[-1] is ",t[-1])
print("Last lement using positive indexing is t[(len(t))-1] is ",t[(len(t))-1])
